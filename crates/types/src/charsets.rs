/// Base character for DRCS encoding.
pub const DRCS_BASE_CHAR: u8 = b'\x1b';

/// Widens a table of `u8` positions to characters.
///
/// Most sets are Latin-1, so their table data is written as bytes; the table
/// itself is `char` because a set such as DEC Special Graphics maps into the
/// box-drawing and symbol blocks.
const fn widen<const N: usize>(bytes: [u8; N]) -> [char; N] {
    let mut table = ['\0'; N];
    let mut index = 0;
    while index < N {
        table[index] = bytes[index] as char;
        index += 1;
    }
    table
}

/// Declares a table whose data is written as bytes and stored as characters.
macro_rules! wide_table {
    [$($byte:expr),* $(,)?] => {
        &widen([$($byte),*])
    };
}

