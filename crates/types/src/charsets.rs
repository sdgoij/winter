#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_ascii_charset_size() {
        assert_eq!(ASCII.len(), 95); // Characters 0x20-0x7E
    }

    #[test]
    fn test_dec_special_graphics_size() {
        // The set covers 0x20 through 0x7E, the same range as ASCII.
        assert_eq!(DEC_SPECIAL_GRAPHICS.len(), 95);
        assert_eq!(DEC_SPECIAL_GRAPHICS[0], ' ');
        assert_eq!(DEC_SPECIAL_GRAPHICS[0x71 - 0x20], '\u{2500}');
        assert_eq!(DEC_SPECIAL_GRAPHICS[0x78 - 0x20], '\u{2502}');
    }

    #[test]
    fn test_charset_constants() {
        assert_eq!(CHARSET_SIZE_94, 94);
        assert_eq!(CHARSET_SIZE_96, 96);
    }
}
