/// DEC Special Character Set and Graphics.
///
/// The 94 positions of `0x20..=0x7D`, plus `0x7E`, which upstream also maps.
/// The data is the VT100 manual's table, as `adapters/charsets.hpp` has it.
pub const DEC_SPECIAL_GRAPHICS: &[char] = &dec_special_graphics();

/// Builds the DEC graphics set: ASCII below `0x5F`, then the drawing symbols.
const fn dec_special_graphics() -> [char; 95] {
    let mut table = ['\0'; 95];
    let mut index = 0;
    while index < 63 {
        table[index] = (0x20 + index as u8) as char;
        index += 1;
    }

    // Positions 0x5F through 0x7E.
    let symbols = [
        ' ',        // Blank
        '\u{2666}', // Diamond
        '\u{2592}', // Checkerboard
        '\u{2409}', // Symbol for horizontal tabulation
        '\u{240C}', // Symbol for form feed
        '\u{240D}', // Symbol for carriage return
        '\u{240A}', // Symbol for line feed
        '\u{00B0}', // Degree
        '\u{00B1}', // Plus/minus
        '\u{2424}', // Symbol for newline
        '\u{240B}', // Symbol for vertical tabulation
        '\u{2518}', // Lower-right corner
        '\u{2510}', // Upper-right corner
        '\u{250C}', // Upper-left corner
        '\u{2514}', // Lower-left corner
        '\u{253C}', // Crossing lines
        '\u{23BA}', // Horizontal line, scan 1
        '\u{23BB}', // Horizontal line, scan 3
        '\u{2500}', // Horizontal line, scan 5
        '\u{23BC}', // Horizontal line, scan 7
        '\u{23BD}', // Horizontal line, scan 9
        '\u{251C}', // Left tee
        '\u{2524}', // Right tee
        '\u{2534}', // Bottom tee
        '\u{252C}', // Top tee
        '\u{2502}', // Vertical bar
        '\u{2264}', // Less than or equal
        '\u{2265}', // Greater than or equal
        '\u{03C0}', // Pi
        '\u{2260}', // Not equal
        '\u{00A3}', // Pound sterling
        '\u{00B7}', // Centred dot
    ];

    let mut offset = 0;
    while offset < symbols.len() {
        table[63 + offset] = symbols[offset];
        offset += 1;
    }
    table
}

